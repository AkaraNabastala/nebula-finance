// Helper to find COA name
export function getAccountName(coaList: COAAccount[], code: string): string {
  const acc = coaList.find((c) => c.code === code);
  return acc ? acc.name : `Akun ${code}`;
}

// Map account ID to COA code dynamically
export function getCOACodeForSource(sourceAccount?: string, banks?: BankAccount[]): string {
  if (!sourceAccount) return '1102'; // default kas besar
  if (sourceAccount === 'kas_kecil') return '1101';
  if (sourceAccount === 'kas_besar') return '1102';
  
  // Dynamic bank lookup
  if (banks && banks.length > 0) {
    const foundBank = banks.find((b) => b.id === sourceAccount || b.accountNumber === sourceAccount);
    if (foundBank && foundBank.coaCode) {
      return foundBank.coaCode;
    }
  }

  // Fallback heuristics
  const lower = sourceAccount.toLowerCase();
  if (lower.includes('bca')) return '1103';
  if (lower.includes('mandiri')) return '1104';
  return '1103'; // default bank
}

/**
 * Otomatis menghasilkan ayat jurnal (Debit = Kredit) untuk transaksi kas & bank
 */
export function createJournalFromTransaction(
  tx: Transaction,
  coaList: COAAccount[],
  journalCount: number,
  banks?: BankAccount[]
): JournalEntry {
  const lines: JournalLine[] = [];
  const srcCode = getCOACodeForSource(tx.sourceAccount, banks);
  const srcName = getAccountName(coaList, srcCode);
  const contraCode = tx.contraAccountCode || (tx.type === 'income' ? '4101' : '5199');
  const contraName = getAccountName(coaList, contraCode);

  if (tx.type === 'income') {
    // Penerimaan: Kas/Bank bertambah di DEBIT, Pendapatan/Lawan bertambah di KREDIT
    lines.push({ accountCode: srcCode, accountName: srcName, debit: tx.amount, credit: 0 });
    lines.push({ accountCode: contraCode, accountName: contraName, debit: 0, credit: tx.amount });
  } else if (tx.type === 'expense') {
    // Pengeluaran: Beban di DEBIT, Kas/Bank berkurang di KREDIT
    lines.push({ accountCode: contraCode, accountName: contraName, debit: tx.amount, credit: 0 });
    lines.push({ accountCode: srcCode, accountName: srcName, debit: 0, credit: tx.amount });
  } else if (tx.type === 'transfer') {
    // Transfer antar akun kas/bank
    const destCode = getCOACodeForSource(tx.destAccount, banks);
    const destName = getAccountName(coaList, destCode);
    lines.push({ accountCode: destCode, accountName: destName, debit: tx.amount, credit: 0 });
    lines.push({ accountCode: srcCode, accountName: srcName, debit: 0, credit: tx.amount });
  }

  const year = tx.date ? tx.date.substring(0, 4) : new Date().getFullYear().toString();
  const code = `JU-${year}-${String(journalCount + 1).padStart(4, '0')}`;

  return {
    id: `ju-auto-${Date.now()}-${Math.random().toString(36).substr(2, 5)}`,
    code,
    date: tx.date,
    type: tx.module === 'kas_kecil' ? 'kas_keluar' : tx.module === 'kas_besar' ? (tx.type === 'income' ? 'kas_masuk' : 'kas_keluar') : 'bank',
    referenceId: tx.id,
    referenceCode: tx.code,
    description: `${tx.description} (${tx.code})`,
    lines,
    totalDebit: tx.amount,
    totalCredit: tx.amount,
    isAutoGenerated: true,
    createdBy: tx.createdBy || 'Sistem Otomatis',
    createdAt: Date.now(),
  };
}

/**
 * Kalkulasi Buku Besar (General Ledger) per akun COA
 */
export interface LedgerEntry {
  date: string;
  journalCode: string;
  referenceCode?: string;
  description: string;
  debit: number;
  credit: number;
  runningBalance: number;
}

export interface AccountLedger {
  account: COAAccount;
  initialBalance: number;
  entries: LedgerEntry[];
  totalDebit: number;
  totalCredit: number;
  endingBalance: number;
}

export function computeGeneralLedger(
  coaList: COAAccount[],
  journals: JournalEntry[]
): Record<string, AccountLedger> {
  const result: Record<string, AccountLedger> = {};

  // Inisialisasi buku besar per akun
  coaList.forEach((acc) => {
    if (!acc.isHeader) {
      result[acc.code] = {
        account: acc,
        initialBalance: acc.initialBalance || 0,
        entries: [],
        totalDebit: 0,
        totalCredit: 0,
        endingBalance: acc.initialBalance || 0,
      };
    }
  });

  // Sort journals chronologically
  const sortedJournals = [...journals].sort((a, b) => a.date.localeCompare(b.date) || a.createdAt - b.createdAt);

  sortedJournals.forEach((j) => {
    j.lines.forEach((line) => {
      const ledger = result[line.accountCode];
      if (ledger) {
        ledger.totalDebit += line.debit;
        ledger.totalCredit += line.credit;

        const isDebitNormal = ledger.account.normalPosition === 'debit';
        const lastBalance = ledger.entries.length > 0 
          ? ledger.entries[ledger.entries.length - 1].runningBalance 
          : ledger.initialBalance;

        const newBalance = isDebitNormal
          ? lastBalance + line.debit - line.credit
          : lastBalance + line.credit - line.debit;

        ledger.entries.push({
          date: j.date,
          journalCode: j.code,
          referenceCode: j.referenceCode,
          description: line.description || j.description,
          debit: line.debit,
          credit: line.credit,
          runningBalance: newBalance,
        });

        ledger.endingBalance = newBalance;
      }
    });
  });

  return result;
}

/**
 * Kalkulasi Neraca Saldo (Trial Balance)
 */
export interface TrialBalanceRow {
  code: string;
  name: string;
  group: string;
  normalPosition: 'debit' | 'credit';
  debit: number;
  credit: number;
}

export function computeTrialBalance(coaList: COAAccount[], journals: JournalEntry[]): {
  rows: TrialBalanceRow[];
  totalDebit: number;
  totalCredit: number;
  isBalanced: boolean;
} {
  const ledger = computeGeneralLedger(coaList, journals);
  const rows: TrialBalanceRow[] = [];
  let totalDebit = 0;
  let totalCredit = 0;

  coaList.forEach((acc) => {
    if (acc.isHeader) return;
    const accLedger = ledger[acc.code];
    const ending = accLedger ? accLedger.endingBalance : (acc.initialBalance || 0);

    let debit = 0;
    let credit = 0;

    if (acc.normalPosition === 'debit') {
      if (ending >= 0) {
        debit = ending;
      } else {
        credit = Math.abs(ending);
      }
    } else {
      if (ending >= 0) {
        credit = ending;
      } else {
        debit = Math.abs(ending);
      }
    }

    if (debit !== 0 || credit !== 0 || (acc.initialBalance && acc.initialBalance > 0)) {
      rows.push({
        code: acc.code,
        name: acc.name,
        group: acc.group,
        normalPosition: acc.normalPosition,
        debit,
        credit,
      });
      totalDebit += debit;
      totalCredit += credit;
    }
  });

  return {
    rows,
    totalDebit,
    totalCredit,
    isBalanced: Math.abs(totalDebit - totalCredit) < 1,
  };
}

/**
 * Kalkulasi Laporan Laba Rugi (Income Statement)
 */
export function computeProfitAndLoss(coaList: COAAccount[], journals: JournalEntry[]) {
  const ledger = computeGeneralLedger(coaList, journals);

  const revenueRows: { code: string; name: string; amount: number }[] = [];
  const expenseRows: { code: string; name: string; amount: number }[] = [];
  let totalRevenue = 0;
  let totalExpense = 0;

  coaList.forEach((acc) => {
    if (acc.isHeader) return;
    const accLedger = ledger[acc.code];
    const amount = accLedger ? accLedger.endingBalance : 0;

    if (acc.group === '4_pendapatan') {
      if (amount !== 0) {
        revenueRows.push({ code: acc.code, name: acc.name, amount });
        totalRevenue += amount;
      }
    } else if (acc.group === '5_beban') {
      if (amount !== 0) {
        expenseRows.push({ code: acc.code, name: acc.name, amount });
        totalExpense += amount;
      }
    }
  });

  const netProfit = totalRevenue - totalExpense;

  return {
    revenueRows,
    totalRevenue,
    expenseRows,
    totalExpense,
    netProfit,
  };
}

/**
 * Kalkulasi Laporan Neraca (Balance Sheet: Aset = Kewajiban + Ekuitas)
 */
export function computeBalanceSheet(coaList: COAAccount[], journals: JournalEntry[]) {
  const ledger = computeGeneralLedger(coaList, journals);
  const { netProfit } = computeProfitAndLoss(coaList, journals);

  const currentAssetRows: { code: string; name: string; amount: number }[] = [];
  const fixedAssetRows: { code: string; name: string; amount: number }[] = [];
  const liabilityRows: { code: string; name: string; amount: number }[] = [];
  const equityRows: { code: string; name: string; amount: number }[] = [];

  let totalCurrentAssets = 0;
  let totalFixedAssets = 0;
  let totalLiabilities = 0;
  let totalEquity = 0;

  coaList.forEach((acc) => {
    if (acc.isHeader) return;
    const accLedger = ledger[acc.code];
    const amount = accLedger ? accLedger.endingBalance : (acc.initialBalance || 0);

    if (acc.group === '1_aset') {
      if (acc.code.startsWith('15')) {
        // Aset Tetap
        const netVal = acc.normalPosition === 'credit' ? -Math.abs(amount) : amount;
        fixedAssetRows.push({ code: acc.code, name: acc.name, amount: netVal });
        totalFixedAssets += netVal;
      } else {
        // Aset Lancar
        currentAssetRows.push({ code: acc.code, name: acc.name, amount });
        totalCurrentAssets += amount;
      }
    } else if (acc.group === '2_kewajiban') {
      liabilityRows.push({ code: acc.code, name: acc.name, amount });
      totalLiabilities += amount;
    } else if (acc.group === '3_modal') {
      equityRows.push({ code: acc.code, name: acc.name, amount });
      totalEquity += amount;
    }
  });

  // Tambahkan Laba Tahun/Bulan Berjalan ke Ekuitas
  equityRows.push({ code: '3999', name: 'Laba Periode Berjalan', amount: netProfit });
  totalEquity += netProfit;

  const totalAssets = totalCurrentAssets + totalFixedAssets;
  const totalLiabilitiesAndEquity = totalLiabilities + totalEquity;

  return {
    currentAssetRows,
    totalCurrentAssets,
    fixedAssetRows,
    totalFixedAssets,
    totalAssets,
    liabilityRows,
    totalLiabilities,
    equityRows,
    totalEquity,
    totalLiabilitiesAndEquity,
    isBalanced: Math.abs(totalAssets - totalLiabilitiesAndEquity) < 1,
  };
}

/**
 * Kalkulasi Laporan Arus Kas (Metode Langsung)
 */
export function computeCashFlow(transactions: Transaction[]) {
  let operatingIn = 0;
  let operatingOut = 0;
  let investingIn = 0;
  let investingOut = 0;
  let financingIn = 0;
  let financingOut = 0;

  const operatingRows: { desc: string; amount: number }[] = [];
  const investingRows: { desc: string; amount: number }[] = [];
  const financingRows: { desc: string; amount: number }[] = [];

  transactions.forEach((tx) => {
    if (tx.type === 'transfer') return; // Transfers between internal accounts don't affect net cash

    if (tx.type === 'income') {
      if (tx.contraAccountCode === '1501' || tx.contraAccountCode === '1502') {
        investingIn += tx.amount;
        investingRows.push({ desc: tx.description, amount: tx.amount });
      } else if (tx.contraAccountCode.startsWith('3') || tx.contraAccountCode === '2201') {
        financingIn += tx.amount;
        financingRows.push({ desc: tx.description, amount: tx.amount });
      } else {
        operatingIn += tx.amount;
        operatingRows.push({ desc: tx.description, amount: tx.amount });
      }
    } else if (tx.type === 'expense') {
      if (tx.contraAccountCode === '1501') {
        investingOut += tx.amount;
        investingRows.push({ desc: tx.description, amount: -tx.amount });
      } else if (tx.contraAccountCode.startsWith('3') || tx.contraAccountCode === '2201') {
        financingOut += tx.amount;
        financingRows.push({ desc: tx.description, amount: -tx.amount });
      } else {
        operatingOut += tx.amount;
        operatingRows.push({ desc: tx.description, amount: -tx.amount });
      }
    }
  });

  const netOperating = operatingIn - operatingOut;
  const netInvesting = investingIn - investingOut;
  const netFinancing = financingIn - financingOut;
  const netCashFlow = netOperating + netInvesting + netFinancing;

  return {
    operatingRows,
    operatingIn,
    operatingOut,
    netOperating,
    investingRows,
    investingIn,
    investingOut,
    netInvesting,
    financingRows,
    financingIn,
    financingOut,
    netFinancing,
    netCashFlow,
  };
}
